// Bake the live inventory into the frontend so the map can open the Postgres,
// Redis and nginx nodes the moment the page loads (the telemetry service then
// replaces it with its own fresh introspection).
//
//   npm run snapshot:inventory                       # node IPs from the Linode API
//   npm run snapshot:inventory -- --db 1.2.3.4 --cache 1.2.3.5 --lb 1.2.3.6
import fs from 'node:fs';
import { collect, INVENTORY_ROLES } from './inventory.js';
import * as linode from './linode.js';

const OUT = new URL('../../../frontend/src/graph/inventorySnapshot.ts', import.meta.url).pathname;

const ips = {};
const argv = process.argv.slice(2);
for (let i = 0; i < argv.length; i += 2) ips[argv[i].replace(/^--/, '')] = argv[i + 1];

if (INVENTORY_ROLES.some((r) => !ips[r]) && linode.hasToken()) {
  for (const inst of await linode.listFleet()) {
    const role = linode.roleOf(inst);
    if (inst.status === 'running' && INVENTORY_ROLES.includes(role) && !ips[role]) ips[role] = linode.ipsOf(inst).publicIp;
  }
}

// Start from the previous snapshot so a role that can't be reached keeps its data.
let roles = {};
try { roles = JSON.parse(fs.readFileSync(OUT, 'utf8').replace(/^[\s\S]*?= /, '')).roles; } catch { /* first run */ }

for (const role of INVENTORY_ROLES) {
  if (!ips[role]) { console.log(`${role}: no node (pass --${role} <ip>)`); continue; }
  const out = await collect(role, ips[role]);
  if (!out) { console.log(`${role}: introspection of ${ips[role]} failed, keeping the previous snapshot`); continue; }
  roles[role] = out;
  console.log(`${role}: ${out.title} (${out.files.length} ${out.noun})`);
}

fs.writeFileSync(OUT, `// Generated by telemetry/src/fleet/snapshot-inventory.js (npm run snapshot:inventory). Do not edit.
// What was inside the fleet's Postgres, Redis and nginx nodes when this was taken.
import type { Codemap } from './types'

export const INVENTORY: Codemap = ${JSON.stringify({ roles }, null, 2)}
`);
console.log(`wrote ${OUT}`);
process.exit(0);
